// Local browser integration test and genuine screenshot capture. Run with `node tests/browser.mjs` while serve.ts runs.
import assert from 'node:assert/strict';
import { readFileSync, statSync, unlinkSync } from 'node:fs';
import { chromium } from '/root/.hermes/profiles/makefun/cache/scratch/pw/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1800, height: 1000 }, acceptDownloads: true, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (!request.url().startsWith('http://127.0.0.1:8080/') && !request.url().startsWith('blob:http://127.0.0.1:8080/')) errors.push(`Network request: ${request.url()}`); });
try {
  await page.goto('http://127.0.0.1:8080/');
  await page.locator('html[data-ready="true"]').waitFor();
  assert.equal(await page.locator('#hero-name').textContent(), 'BOULEVARD SAMPLE');
  await page.locator('[data-size="wide"]').click();
  assert.deepEqual(await page.locator('#cover').evaluate(canvas => [canvas.width, canvas.height]), [1920, 1080]);
  const downloadEvent = page.waitForEvent('download');
  await page.locator('#export').click();
  const download = await downloadEvent;
  assert.equal(download.suggestedFilename(), 'nightshift-wide-1920x1080.png');
  await download.saveAs('screenshots/.export-verification.png');
  const bytes = readFileSync('screenshots/.export-verification.png');
  assert.equal(bytes.readUInt32BE(16), 1920); assert.equal(bytes.readUInt32BE(20), 1080);
  unlinkSync('screenshots/.export-verification.png');
  await page.locator('#cover').screenshot({ path: 'screenshots/1-wide-cover.jpg', type: 'jpeg', quality: 84 });
  await page.locator('[data-size="square"]').click();
  await page.locator('#caption').fill('MIDNIGHT DRIVE');
  await page.locator('[data-palette="electric"]').click();
  await page.locator('#cover').screenshot({ path: 'screenshots/2-square-cover.jpg', type: 'jpeg', quality: 84 });
  await page.screenshot({ path: 'screenshots/3-editor.jpg', type: 'jpeg', quality: 76 });
  await page.locator('[data-size="portrait"]').click();
  await page.locator('[data-layout="columns"]').click();
  await page.locator('[data-palette="golden"]').click();
  await page.locator('#cover').screenshot({ path: 'screenshots/4-portrait-cover.jpg', type: 'jpeg', quality: 84 });
  assert.deepEqual(await page.locator('#cover').evaluate(canvas => [canvas.width, canvas.height]), [1080, 1350]);
  await page.locator('[data-slot="scene"]').click();
  await page.locator('#zoom').fill('150');
  assert.equal(await page.locator('#zoom-value').textContent(), '150%');
  await page.locator('#photo').setInputFiles('app/samples/boulevard.jpg');
  await page.waitForFunction(() => document.querySelector('#scene-name').textContent === 'BOULEVARD.JPG');
  assert.equal(await page.locator('#scene-name').textContent(), 'BOULEVARD.JPG');
  assert.equal(await page.locator('#hero-name').textContent(), 'BOULEVARD.JPG');
  await page.locator('[data-slot="detail"]').click();
  await page.locator('#photo').setInputFiles('app/samples/pier.jpg');
  await page.waitForFunction(() => document.querySelector('#detail-name').textContent === 'PIER.JPG');
  assert.equal(await page.locator('#hero-name').textContent(), 'BOULEVARD.JPG');
  assert.deepEqual(errors, []);
  for (const path of ['1-wide-cover.jpg', '2-square-cover.jpg', '3-editor.jpg', '4-portrait-cover.jpg']) console.log(`${path}: ${statSync('screenshots/' + path).size} bytes`);
  console.log('PASS: offline sample, three sizes, layouts/palettes, local upload, pan/zoom, real PNG download, 4 genuine screenshots');
} finally { await browser.close(); }
